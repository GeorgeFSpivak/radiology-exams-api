

CREATE TABLE radiology_exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT ck_radiology_exams_status
        CHECK ( status IN (
            'REQUESTED',
            'EXAM_PERFORMED',
            'REPORT_IN_PROGRESS',
            'REPORT_FINALIZED',
            'CANCELED'

        ))
);

CREATE TABLE exam_status_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL,
    previous_status VARCHAR(30) NOT NULL,
    new_status VARCHAR(30) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    changed_by VARCHAR(100) NOT NULL,

    CONSTRAINT fk_exam_status_changes_exam
        FOREIGN KEY (exam_id)
        REFERENCES radiology_exams(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_exam_previous_status
        CHECK ( previous_status IN (
            'REQUESTED',
            'EXAM_PERFORMED',
            'REPORT_IN_PROGRESS',
            'REPORT_FINALIZED',
            'CANCELED'
        )),

    CONSTRAINT ck_exam_new_status
        CHECK ( new_status IN (
            'REQUESTED',
            'EXAM_PERFORMED',
            'REPORT_IN_PROGRESS',
            'REPORT_FINALIZED',
            'CANCELED'
        ))
);

CREATE INDEX idx_exam_status_changes_exam_id ON exam_status_changes (exam_id);
